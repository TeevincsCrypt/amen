// Copies ABIs from Foundry's out/ and addresses from deployments/*.json into the frontend.
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const abiDir = join(here, "..", "src", "lib", "abi");
mkdirSync(abiDir, { recursive: true });

const contracts = {
  AmenOracle: "amenOracleAbi",
  VespersVault: "vespersVaultAbi",
  AmenMarket: "amenMarketAbi",
  MockStockToken: "stockTokenAbi",
  MockAggregator: "mockAggregatorAbi",
  MockUSDG: "usdgAbi",
  MockSwapAdapter: "mockSwapAdapterAbi",
};

let index = "";
for (const [name, exportName] of Object.entries(contracts)) {
  const p = join(root, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(p)) {
    console.warn(`skip ${name}: ${p} missing (run forge build)`);
    continue;
  }
  const abi = JSON.parse(readFileSync(p, "utf8")).abi;
  writeFileSync(join(abiDir, `${name}.ts`), `// generated by scripts/sync-contracts.mjs — do not edit\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  index += `export { ${exportName} } from "./${name}";\n`;
}
writeFileSync(join(abiDir, "index.ts"), index);

const depDir = join(root, "deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir)) {
    if (!f.endsWith(".json")) continue;
    const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    deployments[String(d.chainId)] = d;
  }
}
writeFileSync(join(here, "..", "src", "lib", "deployments.json"), JSON.stringify(deployments, null, 2) + "\n");
console.log("synced ABIs:", Object.keys(contracts).join(", "), "| deployments:", Object.keys(deployments).join(", ") || "none");
